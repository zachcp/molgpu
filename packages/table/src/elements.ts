const ATOMIC_NUMBER_BY_SYMBOL = new Map(
  ELEMENT_SYMBOL.map((symbol, atomicNumber) => [symbol, atomicNumber]),
);
for (
  const [symbol, atomicNumber] of Object.entries({
    D: 1,
    T: 1,
    NH: 113,
    MC: 115,
    TS: 117,
    OG: 118,
  })
) ATOMIC_NUMBER_BY_SYMBOL.set(symbol, atomicNumber);

/** Atomic number for an element symbol, or 0 for an unknown symbol. */
export function atomicNumberForSymbol(symbol: string): number {
  return ATOMIC_NUMBER_BY_SYMBOL.get(symbol.toUpperCase()) ?? 0;
}

/** MolQL-compatible uppercase symbol for an atomic number; empty if unknown. */
export function elementSymbolForAtomicNumber(atomicNumber: number): string {
  return Number.isInteger(atomicNumber) && atomicNumber >= 0
    ? ELEMENT_SYMBOL[atomicNumber] ?? ""
    : "";
}
